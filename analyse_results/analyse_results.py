#!/usr/bin/env python3
"""
analyse_results.py — Post-process pipeline results to rank genes by causative probability.

For each patient in results/, reads the most recent report.txt, extracts the final
clinical conclusion, and calls the SLM to rank genes from most to least probable
causative variant.

Output: results_table_{YYYYMMDD}.csv
  - Column 1 : patient_id
  - Column 2+: gene_1, gene_2, ... (most to least probable, deduplicated)

Usage:
    python analyse_results.py
    python analyse_results.py --results-dir /path/to/results
    python analyse_results.py --vllm-url http://localhost:8001
    python analyse_results.py --workers 8
    python analyse_results.py --output-dir /path/to/out
"""

import argparse
import csv
import logging
import re
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

_DEFAULT_RESULTS_DIR = Path(__file__).parent.parent / "results"
_DEFAULT_OUTPUT_DIR  = Path(__file__).parent

# Folder names follow the pattern: {patient_stem}_{YYYYMMDD_HHMMSS}
_TIMESTAMP_RE = re.compile(r"_(\d{8}_\d{6})$")

_RANKING_SYSTEM = "You are an expert clinical geneticist."
_RANKING_PROMPT = """\
Below is the final clinical conclusion section of a variant analysis report.

{text}

Task: List all gene symbols mentioned above, ordered from MOST to LEAST likely \
causative of the patient's condition, based on the reasoning provided.

Rules:
- Output ONLY gene symbols, comma-separated, on a single line.
- Deduplicate: each gene appears at most once.
- Include ALL genes mentioned, even those considered less likely.
- Do not add explanations, numbers, bullet points, or any other text.

Example output: GENE1, GENE2, GENE3
"""


# ─── report parsing ──────────────────────────────────────────────────────────

def _extract_final_conclusion(report_text: str) -> str | None:
    """
    Extract the # Reasoning + # Clinical Conclusion synthesis block from
    the FINAL REPORT section. The synthesis is always the last block before
    the optional appendix (## Variants not included in conclusion).
    """
    final_report_match = re.search(
        r"={60}\nFINAL REPORT\n={60}\n(.*?)(?=\n={60}|\Z)",
        report_text,
        re.DOTALL,
    )
    if not final_report_match:
        return None

    final_report = final_report_match.group(1)

    # The final synthesis block starts with "# Reasoning" (generated by
    # final_conclusion.py). Per-variant conclusion blocks use "# Variant [N]"
    # headers, so rfind("# Reasoning\n") reliably locates the synthesis.
    pos = final_report.rfind("# Reasoning\n")
    if pos == -1:
        # Fallback: report was generated without a Reasoning header
        pos = final_report.rfind("# Clinical Conclusion\n")
    if pos == -1:
        return None

    synthesis = final_report[pos:]

    # Trim everything from the appendix separator onward
    appendix_match = re.search(r"\n---\n\n##\s*Variants not included", synthesis)
    if appendix_match:
        synthesis = synthesis[: appendix_match.start()]

    return synthesis.strip() or None


# ─── gene list parsing ───────────────────────────────────────────────────────

def _parse_gene_list(response: str) -> list[str]:
    """
    Parse the SLM ranking response into an ordered, deduplicated gene list.

    Handles comma-separated, newline-separated, and numbered-list formats.
    Only tokens that look like HGNC gene symbols are kept.
    """
    text = response.strip()

    # Strip common preamble ("The genes are: ...", "Answer: ...", etc.)
    text = re.sub(
        r"^(?:(?:the )?(?:ranked |ordered |most likely )?genes?(?: are)?[^:]*:?\s*)",
        "",
        text,
        flags=re.IGNORECASE,
    )

    # Split on commas or newlines
    parts = re.split(r"[,\n]+", text)

    genes: list[str] = []
    for part in parts:
        token = part.strip()
        # Strip leading numbering: "1." "1)" "1 -" etc.
        token = re.sub(r"^\d+[\.\)\-]\s*", "", token).strip()
        # Strip markdown decoration
        token = re.sub(r"[*_`#]", "", token).strip()
        # Accept tokens that look like gene symbols: start with a letter,
        # contain only alphanumeric chars or hyphens, 2–20 chars total.
        if token and re.fullmatch(r"[A-Za-z][A-Za-z0-9\-]{1,19}", token):
            genes.append(token)

    # Deduplicate preserving order (case-insensitive key)
    seen: set[str] = set()
    unique: list[str] = []
    for g in genes:
        key = g.upper()
        if key not in seen:
            seen.add(key)
            unique.append(g)

    return unique


# ─── result discovery ────────────────────────────────────────────────────────

def _extract_stem(folder_name: str) -> str:
    return _TIMESTAMP_RE.sub("", folder_name)


def _find_latest_reports(results_dir: Path) -> dict[str, Path]:
    """
    For each patient stem, return the report.txt from the most recent run.
    Skips subdirectories with no report.txt or unparseable timestamps.
    """
    best: dict[str, tuple[str, Path]] = {}  # stem -> (timestamp_str, report_path)

    for subdir in sorted(results_dir.iterdir()):
        if not subdir.is_dir():
            continue
        report = subdir / "report.txt"
        if not report.exists():
            logger.debug("[analyse] No report.txt in %s — skipping", subdir.name)
            continue

        ts_match = _TIMESTAMP_RE.search(subdir.name)
        if not ts_match:
            logger.warning("[analyse] Cannot parse timestamp from %s — skipping", subdir.name)
            continue

        stem = _extract_stem(subdir.name)
        ts   = ts_match.group(1)

        existing = best.get(stem)
        if existing is None or ts > existing[0]:
            best[stem] = (ts, report)

    return {stem: report for stem, (_, report) in best.items()}


# ─── per-patient processing ──────────────────────────────────────────────────

def _process_patient(stem: str, report_path: Path, llm) -> tuple[str, list[str]]:
    """
    Read one report, extract the final conclusion, rank genes via SLM.
    Returns (patient_id, ordered_gene_list).
    """
    text = report_path.read_text(encoding="utf-8")
    conclusion = _extract_final_conclusion(text)

    if not conclusion:
        logger.warning("[analyse] No final conclusion found in %s", report_path)
        return stem, []

    logger.info("[analyse] Ranking genes for %s ...", stem)
    prompt   = _RANKING_PROMPT.format(text=conclusion)
    response = llm.generate(
        system=_RANKING_SYSTEM,
        user=prompt,
        max_tokens=120,
        temperature=0.0,
    )

    genes = _parse_gene_list(response)
    logger.info("[analyse] %s → %s", stem, genes)
    return stem, genes


# ─── entry point ─────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Rank causative genes from pipeline reports and write a summary CSV."
    )
    parser.add_argument(
        "--results-dir", type=Path, default=_DEFAULT_RESULTS_DIR, metavar="DIR",
        help=f"Folder containing per-patient result subdirectories (default: {_DEFAULT_RESULTS_DIR})",
    )
    parser.add_argument(
        "--vllm-url", default="http://localhost:8001", metavar="URL",
        help="vLLM HTTP server base URL (default: http://localhost:8001)",
    )
    parser.add_argument(
        "--workers", type=int, default=8, metavar="N",
        help="Number of parallel SLM workers (default: 8)",
    )
    parser.add_argument(
        "--output-dir", type=Path, default=_DEFAULT_OUTPUT_DIR, metavar="DIR",
        help=f"Directory for the output CSV (default: {_DEFAULT_OUTPUT_DIR})",
    )
    args = parser.parse_args()

    if not args.results_dir.is_dir():
        print(f"ERROR: {args.results_dir} is not a directory", file=sys.stderr)
        sys.exit(1)

    reports = _find_latest_reports(args.results_dir)
    if not reports:
        print(f"ERROR: No valid reports found in {args.results_dir}", file=sys.stderr)
        sys.exit(1)

    logger.info("[analyse] %d patient(s) found.", len(reports))

    from pipeline.llm.vllm_client import VLLMClient
    llm = VLLMClient(base_url=args.vllm_url)

    if not llm.is_available():
        print(f"ERROR: vLLM server not reachable at {args.vllm_url}", file=sys.stderr)
        sys.exit(1)

    # Parallel SLM calls — one per patient
    results: dict[str, list[str]] = {}
    workers = min(args.workers, len(reports))
    with ThreadPoolExecutor(max_workers=workers) as pool:
        futures = {
            pool.submit(_process_patient, stem, path, llm): stem
            for stem, path in reports.items()
        }
        for future in as_completed(futures):
            stem = futures[future]
            try:
                _, genes = future.result()
                results[stem] = genes
            except Exception as exc:
                logger.error("[analyse] Failed for patient %s: %s", stem, exc)
                results[stem] = []

    # Build CSV — width = longest gene list across all patients
    max_genes = max((len(g) for g in results.values()), default=0)
    gene_headers = [f"gene_{i + 1}" for i in range(max_genes)]

    today   = datetime.now().strftime("%Y%m%d")
    out_dir = args.output_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"results_table_{today}.csv"

    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["patient_id"] + gene_headers)
        for stem in sorted(results):
            genes = results[stem]
            # Pad shorter rows with empty strings
            row = [stem] + genes + [""] * (max_genes - len(genes))
            writer.writerow(row)

    logger.info("[analyse] Saved → %s", out_path)
    print(out_path)


if __name__ == "__main__":
    main()
